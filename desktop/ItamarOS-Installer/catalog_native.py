def ios_target_blocks(yml: str) -> list[tuple[str, str]]:
    """Return every iOS target; ignore tvOS, macOS and watchOS targets."""
    starts = list(re.finditer(r"^  ([A-Za-z0-9_]+iOS):\s*$", yml, re.MULTILINE))
    all_targets = list(re.finditer(r"^  ([A-Za-z0-9_]+):\s*$", yml, re.MULTILINE))
    result: list[tuple[str, str]] = []
    for match in starts:
        end = min((t.start() for t in all_targets if t.start() > match.start()), default=len(yml))
        result.append((match.group(1), yml[match.end():end]))
    return result


def source_version(yml: str) -> str:
    value = re.search(r'^\s+MARKETING_VERSION:\s*["\']?([0-9][0-9A-Za-z.\-]*)', yml, re.MULTILINE)
    return value.group(1) if value else "Source"


def read_project_yaml(api_json) -> str:
    """API retrieval is preferred over mutable third-party CDNs."""
    item = api_json(f"/repos/{OWNER}/ItamarOS/contents/native-apps/apple/project.yml")
    if not isinstance(item, dict) or item.get("encoding") != "base64":
        raise ValueError("Could not read ItamarOS native app targets.")
    return base64.b64decode(item["content"]).decode("utf-8")


def single_app_release(asset: dict, *, aliases: list[str]) -> bool:
    """Only match explicitly named signed IPAs to avoid offering the wrong app."""
    name = str(asset.get("name") or "").lower()
    if not name.endswith(".ipa") or any(p in name for p in ("unsigned", "-adhoc-", "universal-unsigned")):
        return False
    normal = re.sub(r"[^a-z0-9]+", "", name[:-4])
    return any(normal == re.sub(r"[^a-z0-9]+", "", alias.lower()) or normal.startswith(re.sub(r"[^a-z0-9]+", "", alias.lower()) + "v")
               for alias in aliases)


def native_rows(yml: str, release: dict | None = None) -> list[dict]:
    version = source_version(yml)
    assets = (release or {}).get("assets") or []
    output = []
    for target, block in ios_target_blocks(yml):
        known = TARGETS.get(target, {})
        source_folder = target[:-3]
        found_folder = re.search(r"^\s+- path:\s+([A-Za-z0-9_/-]+)", block, re.MULTILINE)
        if found_folder:
            source_folder = found_folder.group(1).split("/")[0]
        name = known.get("name") or re.sub(r"([a-z])([A-Z])", r"\1 \2", target[:-3]).strip()
        raw_slug = known.get("slug") or re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
        icon = known.get("art") or ""
        if not icon and not known:
            iconset = re.search(r"ASSETCATALOG_COMPILER_APPICON_NAME:\s+([A-Za-z0-9_-]+)", block)
            if iconset:
                icon = f"native-apps/apple/{source_folder}/Assets.xcassets/{iconset.group(1)}.appiconset/Icon.png"
        alias = [name, target[:-3], raw_slug]
        matched = next((a for a in assets if single_app_release(a, aliases=alias)), None)
        ipa = str((matched or {}).get("browser_download_url") or "")
        if ipa and not ipa.startswith(f"https://github.com/{OWNER}/ItamarOS/releases/download/"):
            ipa = ""
        bundle = re.search(r"PRODUCT_BUNDLE_IDENTIFIER:\s+([A-Za-z0-9._-]+)", block)
        output.append({
            "name": name,
            "repo": "ItamarOS",
            "description": known.get("description", "Official native iPhone/iPad app from ItamarOS."),
            "category": known.get("category", "Apps"),
            "version": str((release or {}).get("tag_name") or ("Source " + version)),
            "ipa_url": ipa,
            "release_url": (release or {}).get("html_url", "") if ipa else "",
            "published": str((release or {}).get("published_at") or ""),
            "size_bytes": int((matched or {}).get("size") or 0) if ipa else 0,
            "expected_sha256": (
                str(matched.get("digest", ""))[7:] if matched and re.fullmatch(r"sha256:[0-9a-fA-F]{64}", str(matched.get("digest", ""))) else ""
            ),
            "repository_url": f"https://github.com/{OWNER}/ItamarOS/tree/main/native-apps/apple/{quote(source_folder)}",
            "icon_url": ROOT + icon if icon else "",
            "icon_slug": raw_slug,
            "bundle_id": bundle.group(1) if bundle else "",
            "source_kind": "native_ios",
        })
    return output


def icon_for_repository(name: str) -> tuple[str, str]:
    if name == "ItamarOS-Authenticator":
        return AUTH_ICON, "authenticator"
    return "", re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
